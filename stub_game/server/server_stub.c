/* The three DLL_FUNCTIONS members SV_LoadProgs (engine/server/sv_game.c)
 * calls synchronously during its own load path, not deferred - see the
 * file header comment above for exactly which lines and why these three,
 * only these three. Honest minimal bodies, not real game logic: a string
 * naming what this actually is, and no-ops for the other two. */
static const char *Stub_GetGameDescription( void )
{
	return "Resonance3D stub_game - not a real game, see stub_game/README.md";
}

static void Stub_GameInit( void )
{
}

static void Stub_RegisterEncoders( void )
{
	/* Real games call DELTA_AddEncoder here for custom network encoders.
	 * None exist yet - no custom encoders registered is the honest state,
	 * not a gap, since there is no game data yet that would need one. */
}

int GetEntityAPI2( DLL_FUNCTIONS *pFunctionTable, int *interfaceVersion )
{
	if( !pFunctionTable || !interfaceVersion )
		return 0;

	if( *interfaceVersion != INTERFACE_VERSION )
	{
		/* Real GetEntityAPI2 callers (engine/server/sv_game.c:5274) hand back
		 * their own INTERFACE_VERSION expectation through this same pointer
		 * on mismatch - matching that contract rather than silently failing. */
		*interfaceVersion = INTERFACE_VERSION;
		return 0;
	}

	memset( pFunctionTable, 0, sizeof( DLL_FUNCTIONS ) );
	pFunctionTable->pfnGetGameDescription = Stub_GetGameDescription;
	pFunctionTable->pfnGameInit = Stub_GameInit;
	pFunctionTable->pfnRegisterEncoders = Stub_RegisterEncoders;
	return 1;
}

void GiveFnptrsToDll( enginefuncs_t *engfuncs, globalvars_t *pGlobals )
{
	( void )engfuncs;
	( void )pGlobals;
}
