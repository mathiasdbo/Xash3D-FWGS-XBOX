#!/usr/bin/env python3
"""Write the ordered list of level transitions for the console smoke test.

    python tools/smoke/make-map-list.py --maps "<Half-Life>/valve/maps" --start c0a0 --out tools/smoke/hl-campaign.txt

Reads each retail .bsp's entity lump, collects its trigger_changelevel entities
(map, landmark), and walks the graph from --start the way a player first meets
the maps: a depth-first search, the targets of a map taken in name order. Each
output line is one step the smoke test makes:

    <from> <to> <landmark>      changelevel2 <to> <landmark> from <from>
    <from> <to> -               no transition leads there from <from>: `map <to>`

A step is a real transition while the current map has a trigger_changelevel to
the next one; when the walk has to jump back to an earlier map it is `-`.
Python 3 standard library only.
"""
import argparse
import os
import re
import struct
import sys

ENT_RE = re.compile(r"\{(.*?)\}", re.S)
KV_RE = re.compile(r'"([^"]*)"\s+"([^"]*)"')


def entities(path):
    with open(path, "rb") as f:
        data = f.read()
    version = struct.unpack_from("<i", data, 0)[0]
    if version != 30:
        raise ValueError("%s: BSP version %d, expected 30" % (path, version))
    off, length = struct.unpack_from("<ii", data, 4)
    text = data[off:off + length].split(b"\0")[0].decode("latin-1")
    return [dict(KV_RE.findall(block)) for block in ENT_RE.findall(text)]


def changelevels(maps_dir):
    """{map: [(target, landmark), ...]} in file order"""
    out = {}
    for name in sorted(os.listdir(maps_dir)):
        if not name.endswith(".bsp"):
            continue
        m = name[:-4]
        edges = []
        for e in entities(os.path.join(maps_dir, name)):
            if e.get("classname") == "trigger_changelevel" and e.get("map"):
                edges.append((e["map"].lower(), e.get("landmark", "")))
        out[m] = edges
    return out


def walk(graph, start):
    """first-visit order, each as (from, to, landmark or '-')"""
    seen = {start}
    steps = []
    cur = [start]

    def visit(m):
        for target, landmark in sorted(set(graph.get(m, []))):
            if target in seen or target not in graph:
                continue
            seen.add(target)
            # a real transition only if the map the walk is on has the edge
            if cur[0] == m:
                steps.append((m, target, landmark or "-"))
            else:
                steps.append((cur[0], target, "-"))
            cur[0] = target
            visit(target)

    visit(start)
    return steps


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--maps", required=True, help="the retail valve/maps folder")
    ap.add_argument("--start", default="c0a0")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    graph = changelevels(a.maps)
    if a.start not in graph:
        sys.exit("no %s.bsp in %s" % (a.start, a.maps))
    steps = walk(graph, a.start)
    with open(a.out, "w", newline="\n") as f:
        f.write("# Generated by tools/smoke/make-map-list.py from the retail maps; start %s\n" % a.start)
        f.write("# <from> <to> <landmark>   (- : no transition from <from>, the step is a plain map load)\n")
        f.write("start %s\n" % a.start)
        for s in steps:
            f.write("%s %s %s\n" % s)
    real = sum(1 for s in steps if s[2] != "-")
    print("%d maps in the walk, %d transitions, %d direct loads" % (len(steps) + 1, real, len(steps) - real))
    left = sorted(set(graph) - {a.start} - {s[1] for s in steps})
    print("not reached from %s (%d): %s" % (a.start, len(left), " ".join(left)))


if __name__ == "__main__":
    main()
