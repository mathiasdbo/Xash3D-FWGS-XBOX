#!/usr/bin/env bash
# Generate generated_library_tables.h, the header engine/platform/misc/lib_static.c
# includes at line 27, and (for each library given a real exports.txt) a
# lib_<name>_exports.c defining that library's own export table.
#
# Upstream produces both inside waf, at scripts/waifulib/xshlib.py:74-113, only
# under --static-linking. The Xbox build bypasses xshlib.py entirely (see the X1
# section of docs/r3d/fork-plan.md: no `ld -r`, no `objcopy -G`, no GNU binutils
# in this toolchain), so nothing generates them and lib_static.c does not compile.
#
# That matters more than it looks. -DXASH_STATIC_LIBS=1 in tools/xbox-cc.sh sends
# common/defaults.h:102-105 down the LIB_STATIC branch, which makes
# engine/platform/win32/lib_win.c compile to an empty object (its guard is
# `XASH_LIB == LIB_WIN32`) and leaves lib_static.c as the ONLY definition of
# COM_LoadLibrary, COM_FreeLibrary, COM_GetProcAddress and COM_FunctionFromName.
# A sweep that skips it reports a green tree and the link then fails on four
# undefined symbols the engine needs to load the game at all.
#
# Each argument is name[:exports.txt-path]. A bare name (no colon) still gets
# an entry in the outer libs[] table pointing at lib_<name>_exports, but that
# array's own definition has to come from somewhere else - use this when a
# library's exports file lives somewhere this script cannot generate its own
# definition file for. The X1 stub game module always passes the colon form:
#
#   tools/gen-library-tables.sh out/gen server:stub_game/server/exports.txt client:stub_game/client/exports.txt
#
# Format follows xshlib.py:74-89 exactly, including the anonymous struct type
# that lib_static.c:63 casts to table_t, and the extern-void-then-take-its-
# address idiom write_export_list() uses for every real export regardless of
# its actual signature - correct for what this needs (an opaque function
# pointer looked up by name), matching upstream rather than inventing a
# differently-typed declaration.
#
# An exports.txt with zero lines (a real, deliberate "nothing exported yet"
# state - not a placeholder) generates a valid, empty-but-terminated array,
# same as upstream's own splitlines() would on an empty file.
#
# Each line is `name` or `name asm_symbol` (space-separated, second field
# optional - every exports.txt written before this comment existed has zero
# lines with a space in them, so this is a strictly backward-compatible
# extension, not a format break). The second field exists for exactly one
# real case so far, found compiling the HL SDK's own h_export.cpp (X7.2,
# docs/r3d/fork-plan.md): GiveFnptrsToDll locally redefines DLLEXPORT as
# `__stdcall` on WIN32 instead of `__declspec(dllexport)`, so clang never
# emits a `/EXPORT:` directive for it and its real linker symbol is
# `_GiveFnptrsToDll@8` (stdcall's `@`+argument-byte-count decoration), not
# the plain cdecl name a bare `extern void name(void);` would look for.
# Guessing a calling convention from a name alone is not possible in
# general (the byte count depends on the real signature), so this script
# does not try to - the caller (tools/xbox-gen-exports.sh) determines the
# real symbol from the compiled object's own symbol table and writes it
# here explicitly. With `asm_symbol` given, the generated declaration binds
# to that exact linker symbol via GNU/clang's asm-label extension
# regardless of what calling convention produced it; without it, behaviour
# is unchanged from before this line existed.
set -eu

OUT_DIR="${1:?usage: gen-library-tables.sh <out-dir> [name[:exports.txt-path]...]}"
shift

mkdir -p "$OUT_DIR"
OUT="$OUT_DIR/generated_library_tables.h"

NAMES=()
for arg in "$@"; do
	NAMES+=("${arg%%:*}")
done

{
	echo "/* Generated by tools/gen-library-tables.sh. Do not edit, do not commit."
	echo " * Mirrors scripts/waifulib/xshlib.py:74-80, which the Xbox build bypasses. */"
	echo

	for lib in "${NAMES[@]}"; do
		echo "extern table_t lib_${lib}_exports[];"
	done

	echo
	echo "struct {const char *name;void *func;} libs[] = {"

	for lib in "${NAMES[@]}"; do
		echo "{ \"${lib}\", &lib_${lib}_exports },"
	done

	echo "{0,0}"
	echo "};"
} > "$OUT"

echo "$OUT"

for arg in "$@"; do
	name="${arg%%:*}"
	exports_txt="${arg#*:}"

	# A bare name with no colon leaves $exports_txt equal to $arg (no ':'
	# for the ${arg#*:} strip to act on) - skip generating a definition
	# file for it, per the header comment above.
	[ "$exports_txt" = "$arg" ] && continue

	if [ ! -f "$exports_txt" ]; then
		echo "gen-library-tables: $exports_txt does not exist (for library '$name')" >&2
		exit 1
	fi

	EXPORTS_OUT="$OUT_DIR/generated_lib_${name}_exports.c"
	{
		echo "/* Generated by tools/gen-library-tables.sh from $exports_txt."
		echo " * Do not edit, do not commit. Mirrors scripts/waifulib/xshlib.py:83-89,"
		echo " * which the Xbox build bypasses. */"
		echo "typedef struct {const char *name;void *func;} table_t;"
		echo

		# A name that is not a C identifier (a mangled C++ name, `?Think@CFoo@@QAEXXZ`: XS.2's saved-callback
		# entries) needs its asm symbol and gets a generated identifier; the table row still carries the name.
		n=0
		while IFS=' ' read -r fn asm_sym || [ -n "$fn" ]; do
			[ -z "$fn" ] && continue
			n=$((n + 1))
			if [ -n "${asm_sym:-}" ]; then
				case "$fn" in
				*[!A-Za-z0-9_]*) echo "extern void xs_export_${n}(void) asm(\"${asm_sym}\");" ;;
				*) echo "extern void ${fn}(void) asm(\"${asm_sym}\");" ;;
				esac
			else
				echo "extern void ${fn}(void);"
			fi
		done < "$exports_txt"

		echo
		echo "table_t lib_${name}_exports[] = {"
		n=0
		while IFS=' ' read -r fn asm_sym || [ -n "$fn" ]; do
			[ -z "$fn" ] && continue
			n=$((n + 1))
			case "$fn" in
			*[!A-Za-z0-9_]*) echo "{ \"${fn}\", &xs_export_${n} }," ;;
			*) echo "{ \"${fn}\", &${fn} }," ;;
			esac
		done < "$exports_txt"
		echo "{0,0}"
		echo "};"
	} > "$EXPORTS_OUT"

	echo "$EXPORTS_OUT"
done
