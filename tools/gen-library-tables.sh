#!/usr/bin/env bash
# Generate generated_library_tables.h, the header engine/platform/misc/lib_static.c
# includes at line 27.
#
# Upstream produces it inside waf, at scripts/waifulib/xshlib.py:112, only under
# --static-linking. The Xbox build bypasses xshlib.py entirely (see the X1
# section of docs/r3d/fork-plan.md: no `ld -r`, no `objcopy -G`, no GNU binutils
# in this toolchain), so nothing generates it and lib_static.c does not compile.
#
# That matters more than it looks. -DXASH_STATIC_LIBS=1 in tools/xbox-cc.sh sends
# common/defaults.h:102-105 down the LIB_STATIC branch, which makes
# engine/platform/win32/lib_win.c compile to an empty object (its guard is
# `XASH_LIB == LIB_WIN32`) and leaves lib_static.c as the ONLY definition of
# COM_LoadLibrary, COM_FreeLibrary, COM_GetProcAddress and COM_FunctionFromName.
# A sweep that skips it reports a green tree and the link then fails on four
# undefined symbols the engine needs to load the game at all.
#
# The table is EMPTY today, and that is correct rather than a placeholder: no
# game library is statically linked yet. client and server arrive in X2/X3 with
# the HL SDK, and each needs an exports.txt and a link_helper.c the same way
# xshlib.py builds them. Pass their names as arguments when that happens:
#
#   tools/gen-library-tables.sh out/gen client server
#
# Format follows xshlib.py:74-80 exactly, including the anonymous struct type
# that lib_static.c:63 casts to table_t. The layout matches; the cast is
# upstream's, not ours.
set -eu

OUT_DIR="${1:?usage: gen-library-tables.sh <out-dir> [libname...]}"
shift

mkdir -p "$OUT_DIR"
OUT="$OUT_DIR/generated_library_tables.h"

{
	echo "/* Generated by tools/gen-library-tables.sh. Do not edit, do not commit."
	echo " * Mirrors scripts/waifulib/xshlib.py:74-80, which the Xbox build bypasses. */"
	echo

	for lib in "$@"; do
		echo "extern table_t lib_${lib}_exports[];"
	done

	echo
	echo "struct {const char *name;void *func;} libs[] = {"

	for lib in "$@"; do
		echo "{ \"${lib}\", &lib_${lib}_exports },"
	done

	echo "{0,0}"
	echo "};"
} > "$OUT"

echo "$OUT"
